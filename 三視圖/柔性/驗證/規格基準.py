# ===== 規格查詢 =====
def 取得原廠規格(規格類型='GSG'):
    """根據規格類型回傳對應的原廠規格"""
    if 規格類型 == 'FPC':
        return FPC_原廠規格
    else:
        return GSG_原廠規格


def 取得規格項目(規格類型, 類別, 項目):
    """查詢特定規格項目"""
    規格 = 取得原廠規格(規格類型)
    return 規格.get(類別, {}).get(項目, None)


def 列出非官方規格(規格類型='GSG'):
    """列出所有非官方規格項目"""
    規格 = 取得原廠規格(規格類型)
    非官方 = []
    for 類別, 項目字典 in 規格.items():
        if isinstance(項目字典, dict):
            for 項目名稱, 項目內容 in 項目字典.items():
                if isinstance(項目內容, dict) and not 項目內容.get('官方', True):
                    非官方.append({
                        '類別': 類別,
                        '項目': 項目名稱,
                        '值': 項目內容.get('值'),
                        '單位': 項目內容.get('單位'),
                        '備註': 項目內容.get('備註', '')
                    })
    return 非官方
