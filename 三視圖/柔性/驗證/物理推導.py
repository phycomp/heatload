"""物理推導 - 電性與熱負載的物理公式與推導過程"""

import math


def 推導特性阻抗(佈局):
    """推導特性阻抗 (帶狀線)"""
    εr = 3.3
    w = 佈局.訊號寬度mm
    t = 佈局.訊號厚度mm
    介電層厚度 = sum(層['厚度um'] for 層 in 佈局.層定義 if '介電' in 層['名稱'])
    h = 介電層厚度 / 2 / 1000  # 單側介電層厚度 (mm)
    
    # Wheeler 帶狀線公式
    分母 = 0.67 * math.pi * w * (1 + t / w)
    if 分母 > 0:
        Z0 = (60 / math.sqrt(εr)) * math.log(4 * h / 分母)
    else:
        Z0 = 0
    
    return {
        '公式': 'Z₀ = (60/√εᵣ) · ln(4h / (0.67πw(1 + t/w)))',
        '參數': {
            'εᵣ': εr,
            'w (訊號寬度)': f'{w:.4f} mm',
            't (訊號厚度)': f'{t:.4f} mm',
            'h (單側介電層)': f'{h:.4f} mm',
        },
        '計算結果': f'{Z0:.2f} Ω',
        '物理意義': '帶狀線特性阻抗由幾何比例 h/w 與介電常數決定。h 越大或 w 越小，阻抗越高。',
        '設計建議': '若要調整阻抗至 50Ω，可調整訊號寬度 w 或介電層厚度 h。'
    }


def 推導傳播延遲(佈局):
    """推導傳播延遲"""
    εr = 3.3
    c = 3e8
    tpd = math.sqrt(εr) / c * 1e9
    
    return {
        '公式': 't_pd = √εᵣ / c₀',
        '參數': {
            'εᵣ': εr,
            'c₀': f'{c:.0e} m/s',
        },
        '計算結果': f'{tpd:.3f} ns/m',
        '物理意義': '傳播延遲由介電常數決定，與幾何尺寸無關。εᵣ 越大，訊號傳播越慢。',
        '設計建議': 'Polyimide 的 εᵣ ≈ 3.3，對應 tpd ≈ 5.6 ns/m。若要降低延遲，需選用低 εᵣ 材料。'
    }


def 推導衰減(佈局, 頻率GHz=10, 材料='Ag', 溫度K=300):
    """推導衰減 (導體 + 介電)"""
    f = 頻率GHz * 1e9
    εr = 3.3
    c = 3e8
    
    # 導體衰減
    if 材料 == 'Ag':
        ρ = 0.3e-9 if 溫度K < 10 else 1.59e-8
    else:
        ρ = 0.5e-8 if 溫度K < 10 else 50e-8
    
    μ0 = 4 * math.pi * 1e-7
    δ = math.sqrt(ρ / (math.pi * f * μ0)) if f > 0 else 1
    Rs = ρ / δ if δ > 0 else 0
    Z0 = 50  # 假設
    w = 佈局.訊號寬度mm * 1e-3
    αc = (Rs / (Z0 * w)) * 8.686 if w > 0 and Z0 > 0 else 0
    
    # 介電衰減
    tanδ = 0.001 if 溫度K < 10 else 0.002
    αd = (math.pi * f / c) * math.sqrt(εr) * tanδ * 8.686
    
    return {
        '公式': 'α = αc + αd\nαc = (Rs / (Z₀·w)) · 8.686\nαd = (πf√εᵣ·tanδ / c₀) · 8.686',
        '參數': {
            'f': f'{頻率GHz} GHz',
            '材料': 材料,
            '溫度': f'{溫度K} K',
            '電阻率 ρ': f'{ρ:.2e} Ω·m',
            '集膚深度 δ': f'{δ*1e6:.3f} μm',
            '表面電阻 Rs': f'{Rs:.4f} Ω/sq',
            '損耗正切 tanδ': tanδ,
        },
        '導體衰減 αc': f'{αc:.3f} dB/m',
        '介電衰減 αd': f'{αd:.3f} dB/m',
        '總衰減 α': f'{αc + αd:.3f} dB/m',
        '物理意義': '導體衰減 ∝ √f (集膚效應)，介電衰減 ∝ f (損耗正切)。高頻時介電衰減主導。',
        '設計建議': '降低衰減：選用低 tanδ 材料、降低 ρ (低溫/超導)、增加 w 或 h。'
    }


def 推導熱負載(佈局, ΔT=36, 長度m=0.4, 材料='Ag'):
    """推導熱負載"""
    # 導體截面積
    w = 佈局.訊號寬度mm * 1e-3  # m
    t = 佈局.訊號厚度mm * 1e-3  # m
    A = w * t  # m²
    
    # 熱導率 (Wiedemann-Franz)
    L0 = 2.44e-8  # WΩ/K²
    T = 20  # 平均溫度 (K)
    
    if 材料 == 'Ag':
        ρ = 0.3e-9 if T < 10 else 1.59e-8
    else:
        ρ = 0.5e-8 if T < 10 else 50e-8
    
    κ = L0 * T / ρ if ρ > 0 else 0
    
    # 熱負載
    Q = κ * A * ΔT / 長度m if 長度m > 0 else 0
    
    # 轉為 μW
    Q_μW = Q * 1e6
    
    return {
        '公式': 'Q = κ·A·ΔT / L\nκ = L₀·T / ρ (Wiedemann-Franz)',
        '參數': {
            'ΔT': f'{ΔT} K',
            '長度 L': f'{長度m} m',
            '材料': 材料,
            '截面積 A': f'{A*1e12:.2f} μm²',
            '熱導率 κ': f'{κ:.2f} W/m·K',
        },
        '計算結果': f'{Q_μW:.2f} μW/ch',
        '物理意義': '熱負載由電子熱傳導主導。截面積越小、長度越長、電阻率越低，熱負載越小。',
        '設計建議': '降低熱負載：使用 NbTi (低溫超導)、減小訊號層厚度、增加長度、控制 PTH 熱路徑。'
    }


def 取得所有推導(佈局, 材料='Ag', 溫度K=300):
    """取得所有物理推導"""
    return {
        '特性阻抗': 推導特性阻抗(佈局),
        '傳播延遲': 推導傳播延遲(佈局),
        '衰減': 推導衰減(佈局, 10, 材料, 溫度K),
        '熱負載': 推導熱負載(佈局, 36, 0.4, 材料),
    }
