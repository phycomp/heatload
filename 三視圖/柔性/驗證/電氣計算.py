# 柔性線函式庫/驗證/電氣計算.py
"""電氣特性計算 - 精確版 (阻抗、衰減、傳播延遲、串擾)"""

import math


# ===== 材料常數 =====
材料常數 = {
    'Ag': {
        '電阻率_300K': 1.59e-8,    # Ω·m
        '電阻率_4K': 0.3e-9,       # Ω·m (RRR > 100)
        '相對磁導率': 1.0,
    },
    'NbTi': {
        '電阻率_300K': 50e-8,      # Ω·m
        '電阻率_10K': 0.5e-8,      # Ω·m (正常態)
        '臨界溫度': 9.8,           # K
    },
    'Polyimide': {
        '介電常數': 3.3,
        '損耗正切': 0.002,         # @ 10 GHz
        '損耗正切_低溫': 0.001,    # @ 4K
    },
}

# 物理常數
光速 = 3e8              # m/s
真空磁導率 = 4 * math.pi * 1e-7  # H/m
真空介電常數 = 8.854e-12         # F/m


def 計算特性阻抗(佈局, 溫度K=300):
    """
    計算帶狀線特性阻抗 (Stripline) - 精確公式
    
    使用 IPC-2141 帶狀線公式:
    Z0 = (60 / √εr) * ln(4h / (0.67πw(1 + t/w)))
    
    參數:
        佈局: 佈局計算器實例
        溫度K: 工作溫度 (K)
    
    回傳:
        特性阻抗 (Ω)
    """
    εr = 材料常數['Polyimide']['介電常數']
    
    # 幾何參數 (mm)
    w = 佈局.訊號寬度mm
    t = 佈局.訊號厚度mm
    
    # 計算介電層總厚度 (mm)
    介電層厚度 = sum(層['厚度um'] for 層 in 佈局.層定義 if '介電' in 層['名稱'])
    h = 介電層厚度 / 2 / 1000  # 單側介電層厚度 (mm)
    
    if w <= 0 or h <= 0 or t <= 0:
        return 0
    
    # 帶狀線阻抗公式
    try:
        分母 = 0.67 * math.pi * w * (1 + t / w)
        if 分母 <= 0 or 4 * h / 分母 <= 0:
            return 0
        Z0 = (60 / math.sqrt(εr)) * math.log(4 * h / 分母)
    except (ValueError, ZeroDivisionError):
        return 0
    
    return Z0


def 計算傳播延遲(佈局, 溫度K=300):
    """
    計算傳播延遲 (精確版)
    
    公式: tpd = √εr / c
    
    參數:
        佈局: 佈局計算器實例
        溫度K: 工作溫度 (K)
    
    回傳:
        傳播延遲 (ns/m)
    """
    εr = 材料常數['Polyimide']['介電常數']
    tpd = math.sqrt(εr) / 光速 * 1e9  # ns/m
    return tpd


def 計算表面電阻(頻率Hz, 材料='Ag', 溫度K=300):
    """
    計算表面電阻 (包含集膚效應)
    
    參數:
        頻率Hz: 頻率 (Hz)
        材料: 'Ag' 或 'NbTi'
        溫度K: 工作溫度 (K)
    
    回傳:
        表面電阻 (Ω/square)
    """
    if 材料 == 'Ag':
        if 溫度K < 10:
            ρ = 材料常數['Ag']['電阻率_4K']
        else:
            ρ = 材料常數['Ag']['電阻率_300K']
    elif 材料 == 'NbTi':
        if 溫度K < 10:
            ρ = 材料常數['NbTi']['電阻率_10K']
        else:
            ρ = 材料常數['NbTi']['電阻率_300K']
    else:
        ρ = 1.59e-8
    
    # 集膚深度
    if 頻率Hz <= 0:
        return 0
    δ = math.sqrt(ρ / (math.pi * 頻率Hz * 真空磁導率))
    
    if δ <= 0:
        return 0
    
    # 表面電阻
    Rs = ρ / δ
    return Rs


def 計算導體衰減(佈局, 頻率GHz=10, 材料='Ag', 溫度K=300):
    """
    計算導體衰減 (精確版)
    
    公式: αc = (Rs / (Z0 * w)) * 8.686  (dB/m)
    
    參數:
        佈局: 佈局計算器實例
        頻率GHz: 頻率 (GHz)
        材料: 'Ag' 或 'NbTi'
        溫度K: 工作溫度 (K)
    
    回傳:
        導體衰減 (dB/m)
    """
    f = 頻率GHz * 1e9
    Rs = 計算表面電阻(f, 材料, 溫度K)
    Z0 = 計算特性阻抗(佈局, 溫度K)
    
    w = 佈局.訊號寬度mm * 1e-3  # 轉為 m
    
    if w <= 0 or Z0 <= 0:
        return 0
    
    # 導體衰減 (dB/m)
    αc = (Rs / (Z0 * w)) * 8.686
    return αc


def 計算介電衰減(佈局, 頻率GHz=10, 溫度K=300):
    """
    計算介電衰減 (精確版)
    
    公式: αd = (π * f / c) * √εr * tanδ * 8.686  (dB/m)
    
    參數:
        佈局: 佈局計算器實例
        頻率GHz: 頻率 (GHz)
        溫度K: 工作溫度 (K)
    
    回傳:
        介電衰減 (dB/m)
    """
    f = 頻率GHz * 1e9
    εr = 材料常數['Polyimide']['介電常數']
    
    # 低溫下損耗正切較低
    if 溫度K < 10:
        tanδ = 材料常數['Polyimide']['損耗正切_低溫']
    else:
        tanδ = 材料常數['Polyimide']['損耗正切']
    
    # 介電衰減 (dB/m)
    αd = (math.pi * f / 光速) * math.sqrt(εr) * tanδ * 8.686
    return αd


def 計算插入損耗(佈局, 頻率GHz=10, 材料='Ag', 溫度K=300):
    """
    計算總插入損耗 (導體 + 介電)
    
    參數:
        佈局: 佈局計算器實例
        頻率GHz: 頻率 (GHz)
        材料: 'Ag' 或 'NbTi'
        溫度K: 工作溫度 (K)
    
    回傳:
        總插入損耗 (dB/m)
    """
    αc = 計算導體衰減(佈局, 頻率GHz, 材料, 溫度K)
    αd = 計算介電衰減(佈局, 頻率GHz, 溫度K)
    return αc + αd


def 計算衰減頻譜(佈局, 材料='Ag', 溫度K=4):
    """
    計算衰減頻譜 (2, 6, 12, 18 GHz)
    
    參數:
        佈局: 佈局計算器實例
        材料: 'Ag' 或 'NbTi'
        溫度K: 工作溫度 (K)
    
    回傳:
        dict: {頻率GHz: 衰減dB/m}
    """
    頻率列表 = [2, 6, 12, 18]
    結果 = {}
    for f in 頻率列表:
        結果[f] = 計算插入損耗(佈局, f, 材料, 溫度K)
    return 結果


def 計算串擾(佈局, 頻率GHz=10, 長度mm=200):
    """
    計算相鄰通道串擾 (簡化模型)
    
    基於耦合傳輸線理論，串擾隨距離和頻率變化
    
    參數:
        佈局: 佈局計算器實例
        頻率GHz: 頻率 (GHz)
        長度mm: 線長度 (mm)
    
    回傳:
        串擾 (dB)
    """
    # 通道間距 (mm)
    s = 佈局.訊號間距
    # 介電層厚度 (mm)
    h = sum(層['厚度um'] for 層 in 佈局.層定義 if '介電' in 層['名稱']) / 2 / 1000
    
    if s <= 0 or h <= 0:
        return -100
    
    # 耦合係數 (簡化)
    k = h / s
    # 串擾估算 (dB)
    # 頻率越高、長度越長，串擾越大
    串擾 = -60 + 20 * math.log10(頻率GHz / 10) + 20 * math.log10(長度mm / 200)
    
    return 串擾
