# 柔性線函式庫/驗證/設計建議.py
"""設計建議 - 根據失敗原因提供物理推導的改善方向"""


def 分析失敗原因(項目名稱, 規格值, 原廠值, 差異, 佈局):
    """分析單一失敗項目的原因並提供建議"""
    建議 = {
        '項目': 項目名稱,
        '失敗原因': '',
        '物理推導': '',
        '設計方向': [],
    }
    
    # ===== 幾何相關 =====
    if '總厚度' in 項目名稱:
        建議['失敗原因'] = f'當前總厚度 {規格值}μm 與 CF3 標準 {原廠值}μm 差異 {差異:+.1f}μm'
        建議['物理推導'] = 'CF3 的 300μm 由 7 層結構決定。厚度影響阻抗 (h) 與機械柔性。'
        建議['設計方向'] = [
            '增加介電層厚度至 129μm 級別',
            '或將結構重新定位為「超薄版本」，非直接對標 CF3',
            '調整後需重新驗證特性阻抗 (Z₀ ∝ h)',
        ]
    
    elif '總寬度' in 項目名稱:
        建議['失敗原因'] = f'當前總寬度 {規格值}mm 與 CF3 標準 {原廠值}mm 差異 {差異:+.1f}mm'
        建議['物理推導'] = 'CF3 的 17mm = 8通道 × 2mm間距 + 邊緣間距。寬度決定連接器相容性。'
        建議['設計方向'] = [
            '擴展總寬度至 17mm 以符合 CF3 幾何',
            '或減少通道數 (4通道 × 2mm + 1mm = 9mm)',
            '維持通道間距 ≥ 2mm 以避免串擾惡化',
        ]
    
    elif '通道間距' in 項目名稱:
        建議['失敗原因'] = f'當前間距 {規格值}mm 與 CF3 標準 {原廠值}mm 差異 {差異:+.2f}mm'
        建議['物理推導'] = '間距越小，相鄰通道耦合越強，串擾越嚴重。'
        建議['設計方向'] = [
            '將通道間距調整至 2mm 以符合 CF3',
            '若需縮小間距，需增加接地層屏蔽或降低頻率',
        ]
    
    elif '訊號寬度' in 項目名稱:
        建議['失敗原因'] = f'當前寬度 {規格值}μm 與 CF3 標準 {原廠值}μm 差異 {差異:+.1f}μm'
        建議['物理推導'] = '訊號寬度影響特性阻抗 (w↑ → Z₀↓) 與熱負載 (A↑ → Q↑)。'
        建議['設計方向'] = [
            '調整訊號寬度以匹配 50Ω 阻抗',
            '若需降低熱負載，可減小訊號寬度',
        ]
    
    # ===== 層結構相關 =====
    elif '層數' in 項目名稱:
        建議['失敗原因'] = f'當前層數 {規格值} 與 CF3 標準 {原廠值} 不符'
        建議['物理推導'] = 'CF3 為 7 層 GSG 結構，FPC 為 11 層 NbTi 結構。'
        建議['設計方向'] = [
            '確認目標規格：GSG 7層 或 FPC 11層',
            '若目標為 CF3，使用 7 層結構',
        ]
    
    # ===== 電氣相關 =====
    elif '特性阻抗' in 項目名稱:
        建議['失敗原因'] = f'當前阻抗 {規格值}Ω 與目標 50Ω 差異 {差異:+.2f}Ω'
        建議['物理推導'] = 'Z₀ = (60/√εᵣ)·ln(4h/(0.67πw(1+t/w)))。h↑ → Z₀↑，w↑ → Z₀↓。'
        建議['設計方向'] = [
            f'調整訊號寬度 w (當前 {佈局.訊號寬度mm*1000:.0f}μm)',
            f'調整介電層厚度 h',
            '或調整介電常數 εᵣ (選用不同材料)',
        ]
    
    elif '傳播延遲' in 項目名稱:
        建議['失敗原因'] = f'當前延遲 {規格值}ns/m 與目標 5.6ns/m 差異 {差異:+.3f}'
        建議['物理推導'] = 't_pd = √εᵣ / c₀。與幾何無關，僅取決於介電常數。'
        建議['設計方向'] = [
            'Polyimide 的 εᵣ ≈ 3.3，對應 tpd ≈ 5.6 ns/m',
            '若要改變延遲，需選用不同 εᵣ 的材料',
        ]
    
    elif '插入損耗' in 項目名稱:
        建議['失敗原因'] = f'當前衰減 {規格值}dB/m 超出目標 {原廠值}dB/m'
        建議['物理推導'] = 'α = αc + αd。αc ∝ √f·ρ，αd ∝ f·tanδ。'
        建議['設計方向'] = [
            '改用 NbTi 超導平台 (低溫下 ρ→0)',
            '選用低 tanδ 介電材料',
            '增加訊號寬度 w (降低 αc)',
            '將目標調整為 NbTi 平台 ~2-3 dB/m @ 10GHz',
        ]
    
    elif '串擾' in 項目名稱:
        建議['失敗原因'] = f'當前串擾 {規格值}dB 超出目標 {原廠值}dB'
        建議['物理推導'] = '串擾 ∝ h/s (介電層厚度/通道間距)。間距 s↑ → 串擾↓。'
        建議['設計方向'] = [
            '增加通道間距 s 至 2mm',
            '增加接地層屏蔽',
            '降低工作頻率',
        ]
    
    # ===== 熱性能相關 =====
    elif '熱負載' in 項目名稱:
        建議['失敗原因'] = f'當前熱負載 {規格值} 超出目標 {原廠值}'
        建議['物理推導'] = 'Q = κ·A·ΔT / L。κ = L₀T/ρ。A = w·t。'
        建議['設計方向'] = [
            '使用 NbTi 超導平台 (Tc = 9.8K，低溫下 κ 極低)',
            '減小訊號層厚度 t (FPC 的 0.2μm 優於 GSG 的 2μm)',
            '增加線長度 L',
            '控制 PTH 熱路徑 (銅熱導率高)',
        ]
    
    # ===== 機械相關 =====
    elif '拉伸力' in 項目名稱 or '彎曲' in 項目名稱:
        建議['失敗原因'] = f'當前 {規格值} 與目標 {原廠值} 不符'
        建議['物理推導'] = '機械強度取決於材料與結構設計。'
        建議['設計方向'] = [
            '增加保護層厚度以提升機械強度',
            '選用高強度材料',
        ]
    
    else:
        建議['失敗原因'] = f'當前值 {規格值} 與原廠值 {原廠值} 差異 {差異:+.3f}'
        建議['物理推導'] = '請參考相關物理公式。'
        建議['設計方向'] = ['請檢視設計參數並調整。']
    
    return 建議


def 產生設計建議報告(驗證結果, 佈局):
    """產生完整設計建議報告"""
    失敗項目列表 = []
    
    for 類別, 結果列表 in 驗證結果.items():
        for 項目 in 結果列表:
            if not 項目['通過']:
                建議 = 分析失敗原因(
                    項目['項目'],
                    項目['規格值'],
                    項目['原廠值'],
                    項目['差異'],
                    佈局
                )
                建議['類別'] = 類別
                失敗項目列表.append(建議)
    
    return 失敗項目列表
