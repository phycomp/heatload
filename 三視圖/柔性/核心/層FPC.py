def 計算各層位置(規格層):
    """計算各層位置 (單位: mm)"""
    總厚度um, 中心偏移=0., 0.
    中心索引 = len(規格層) // 2
    for 層列表 in 規格層:
      # print(['層列表', 層列表])
      總厚度um += 層列表['厚度um']  #sum(層 for 層 in if '厚度um' in 層)
    for 層列表 in 規格層[:中心索引]:
      中心偏移 += 層列表['厚度um']
    中心偏移 += 規格層[中心索引]['厚度um'] / 2

      # 找出訊號層索引
    # 訊號索引 = [i for i, 層 in enumerate(層列表) if 層['是訊號層']]

    # 使用中間層作為中心參考

    累積um = -中心偏移
    位置列表 = []
    for 層列表 in 規格層:
        厚度um = 層列表['厚度um']
        位置列表.append({
            '下緣um': 累積um,
            '上緣um': 累積um + 厚度um,
            '下緣mm': 累積um / 1000,
            '上緣mm': (累積um + 厚度um) / 1000,
            '中心mm': (累積um + 厚度um / 2) / 1000,
            '厚度mm': 厚度um / 1000,
            '厚度um': 厚度um
        })
        累積um += 厚度um

    return 位置列表, 總厚度um


def 計算H1H2(層列表):
    """計算 H1 與 H2 尺寸"""
    位置列表, _ = 計算各層位置(層列表)

    # 找出 L1, L2, L3 的中心位置
    L1中心 = None
    L2中心 = None
    L3中心 = None

    for i, 層 in enumerate(層列表):
        if 'L1' in 層['名稱']:
            L1中心 = 位置列表[i]['中心mm']
        elif 'L2' in 層['名稱']:
            L2中心 = 位置列表[i]['中心mm']
        elif 'L3' in 層['名稱']:
            L3中心 = 位置列表[i]['中心mm']

    H1 = abs(L2中心 - L1中心) * 1000 if L1中心 and L2中心 else 0
    H2 = abs(L3中心 - L2中心) * 1000 if L2中心 and L3中心 else 0

    return H1, H2


