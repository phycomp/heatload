# 柔性線函式庫/核心/佈局計算.py
"""佈局計算器 - 計算所有幾何參數"""

from .層 import 層定義, 計算各層位置

class 佈局計算器:
    """佈局計算器 - 計算柔性線的所有幾何參數"""

    def __init__(self, 通道數=8, 訊號間距=2., 訊號寬度um=35, 線總寬=17., 線長度=200, 訊號厚度um=2., 鈦比例=53., 線情境='讀取'):

        self.層位置列表, self.總厚度um = 計算各層位置(層定義)
        self.通道數 = 通道數
        self.線總寬 = 線總寬
        self.線長度 = 線長度
        self.訊號間距 = 訊號間距
        self.訊號寬度mm = 訊號寬度um / 1000.0
        self.訊號厚度mm = 訊號厚度um / 1000.0
        self.總厚度mm = self.總厚度um / 1000.0
        self.鈦比例 = 鈦比例
        self.鈮鈦比例 = f'{100 - 鈦比例:.0f}:{鈦比例:.0f}'
        self.超導相變溫度 = '9.2'
        self.操作溫區=f'4～{self.超導相變溫度}'  #9.2K
        self.超導臨界電流密度 = '2.5 × 10⁵'  # 9.2K'
        self.長寬高 = f'{self.線長度}x{self.線總寬:.0f}x{self.總厚度mm:.1f}'
        self.線情境 = 線情境

        # 計算邊緣
        #self.邊緣 = (self.線總寬 - self.訊號間距 * (self.通道數 - 1) - self.訊號寬度mm) / 2.0
        # 計算邊緣間距 (兩側間距)
        self.邊緣間距 = (self.線總寬 - self.訊號間距 * (self.通道數 - 1) - self.訊號寬度mm) / 2.0
        self.左側間距 = self.邊緣間距
        self.右側間距 = self.邊緣間距
        self.總間距 = self.左側間距 + self.右側間距  # 兩側間距總和

        # 取得各層中心與厚度 (方便繪圖使用)
        self.層中心列表 = [位置['中心mm'] for 位置 in self.層位置列表]
        self.層厚度列表 = [位置['厚度mm'] for 位置 in self.層位置列表]
