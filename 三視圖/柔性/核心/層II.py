def 計算各層位置(層定義列表):
    """計算各層位置 (單位: mm)"""
    位置列表 = []
    總厚度um = sum(層['厚度um'] for 層 in 層定義列表)

    # 找出訊號層索引
    訊號索引 = [i for i, 層 in enumerate(層定義列表) if 層['是訊號層']]
    
    # 使用中間層作為中心參考
    中心參考索引 = len(層定義列表) // 2
    中心偏移 = sum(層['厚度um'] for 層 in 層定義列表[:中心參考索引]) + 層定義列表[中心參考索引]['厚度um'] / 2

    累積um = -中心偏移
    for 層 in 層定義列表:
        厚度um = 層['厚度um']
        位置列表.append({
            '下緣um': 累積um,
            '上緣um': 累積um + 厚度um,
            '下緣mm': 累積um / 1000,
            '上緣mm': (累積um + 厚度um) / 1000,
            '中心mm': (累積um + 厚度um / 2) / 1000,
            '厚度mm': 厚度um / 1000,
            '厚度um': 厚度um
        })
        累積um += 厚度um

    return 位置列表, 總厚度um
