def 測試層定義():
    """測試層定義是否完整"""
    print("=" * 50)
    print("測試 1: 層定義")
    print("=" * 50)
    
    assert len(層定義) == 7, f"預期7層，實際{len(層定義)}層"
    print(f"✅ 層數: {len(層定義)}")
    
    層名稱列表 = [層['名稱'] for 層 in 層定義]
    預期名稱 = ['保護層-底', '接地層-底', '介電層-下', '訊號線', '介電層-上', '接地層-上', '保護層-上']
    assert 層名稱列表 == 預期名稱, f"層名稱不符"
    print(f"✅ 層名稱: {層名稱列表}")
    
    總厚度 = sum(層['厚度um'] for 層 in 層定義)
    預期厚度 = 15 + 5 + 129 + 2 + 129 + 5 + 15  # 300um
    assert 總厚度 == 預期厚度, f"總厚度 {總厚度}um 不等於 {預期厚度}um"
    print(f"✅ 總厚度: {總厚度}um")
    print()


def 測試各層位置():
    """測試各層位置計算"""
    print("=" * 50)
    print("測試 2: 各層位置計算")
    print("=" * 50)
    
    位置列表, 總厚度 = 計算各層位置()
    
    assert len(位置列表) == 7, f"預期7個位置，實際{len(位置列表)}個"
    print(f"✅ 位置數量: {len(位置列表)}")
    
    # 檢查對稱性：訊號線應該在中心 (y=0)
    訊號索引 = 3  # 第4層是訊號線
    訊號中心 = 位置列表[訊號索引]['中心mm']
    assert abs(訊號中心) < 0.001, f"訊號線中心 {訊號中心}mm 應為 0"
    print(f"✅ 訊號線中心: {訊號中心:.3f}mm (在中心)")
    
    # 檢查對稱：上3層與下3層應對稱
    下層厚度 = [位置列表[i]['厚度um'] for i in range(3)]
    上層厚度 = [位置列表[i]['厚度um'] for i in range(4, 7)]
    assert 下層厚度 == 上層厚度[::-1], f"上下不對稱: 下{下層厚度} vs 上{上層厚度}"
    print(f"✅ 上下對稱: 下{下層厚度} | 上{上層厚度[::-1]}")
    
    # 檢查總厚度
    assert 總厚度 == 300, f"總厚度 {總厚度}um 應為 300um"
    print(f"✅ 總厚度: {總厚度}um")
    
    # 顯示各層位置
    print("\n各層位置 (mm):")
    for i, 位置 in enumerate(位置列表):
        print(f"  {層定義[i]['名稱']:8} | 下緣: {位置['下緣mm']:7.3f} | "
              f"中心: {位置['中心mm']:7.3f} | 上緣: {位置['上緣mm']:7.3f} | "
              f"厚度: {位置['厚度mm']:5.3f}mm")
    print()


def 測試佈局計算器():
    """測試佈局計算器"""
    print("=" * 50)
    print("測試 3: 佈局計算器")
    print("=" * 50)
    
    # 預設參數 (8通道)
    佈局 = 佈局計算器()
    print(f"✅ 建立佈局: {佈局.通道數}通道")
    
    # 測試屬性
    assert 佈局.通道數 == 8, f"通道數應為8，實際{佈局.通道數}"
    assert 佈局.總厚度um == 300, f"總厚度應為300um，實際{佈局.總厚度um}"
    assert 佈局.總厚度mm == 0.3, f"總厚度應為0.3mm，實際{佈局.總厚度mm}"
    assert 佈局.鈮鈦比例 == "47:53", f"鈮鈦比例應為47:53，實際{佈局.鈮鈦比例}"
    print(f"✅ 基本屬性: 通道數={佈局.通道數}, 總厚度={佈局.總厚度um}um, 比例={佈局.鈮鈦比例}")
    
    # 測試邊緣計算
    預期邊緣 = (17.0 - 2.0 * 7 - 0.035) / 2  # (總寬 - 間距*7 - 訊號寬) / 2
    assert abs(佈局.邊緣 - 預期邊緣) < 0.001, f"邊緣 {佈局.邊緣} 不等於 {預期邊緣}"
    print(f"✅ 邊緣計算: {佈局.邊緣:.3f}mm")
    
    # 測試不同通道數
    佈局4ch = 佈局計算器(通道數=4)
    assert 佈局4ch.通道數 == 4, f"通道數應為4，實際{佈局4ch.通道數}"
    佈局4ch_邊緣 = (17.0 - 2.0 * 3 - 0.035) / 2
    assert abs(佈局4ch.邊緣 - 佈局4ch_邊緣) < 0.001, f"4ch邊緣計算錯誤"
    print(f"✅ 4通道邊緣: {佈局4ch.邊緣:.3f}mm")
    
    # 測試不同總寬
    佈局窄 = 佈局計算器(線總寬=10.0)
    assert 佈局窄.線總寬 == 10.0, f"線總寬應為10.0，實際{佈局窄.線總寬}"
    print(f"✅ 自訂總寬: {佈局窄.線總寬}mm")
    
    # 顯示所有屬性
    print(f"\n佈局屬性:")
    print(f"  通道數: {佈局.通道數}")
    print(f"  訊號間距: {佈局.訊號間距}mm")
    print(f"  訊號寬度: {佈局.訊號寬度mm:.3f}mm")
    print(f"  線總寬: {佈局.線總寬:.2f}mm")
    print(f"  線長度: {佈局.線長度}mm")
    print(f"  總厚度: {佈局.總厚度um}um ({佈局.總厚度mm:.1f}mm)")
    print(f"  邊緣: {佈局.邊緣:.3f}mm")
    print(f"  長寬高: {佈局.長寬高}")
    print(f"  鈮鈦比例: {佈局.鈮鈦比例}")
    print()


