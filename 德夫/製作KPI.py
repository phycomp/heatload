print(f"\n各年度KPI數量:")
print(df_all.groupby('年度').size())
print(f"\n各單位KPI數量:")
print(df_all.groupby('負責單位').size())
print(f"\n各年度各單位KPI數量:")
print(df_all.groupby(['年度', '負責單位']).size().unstack(fill_value=0))

# 儲存Excel
output_path = './量子傳輸線三年KPI計畫_研發製程應工品保.xlsx'
with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
    df_all.to_excel(writer, sheet_name='三年KPI總表', index=False)
    df_y1[['年度', 'KPI類別', 'KPI項目', '目標值', '權重', '負責單位']].to_excel(writer, sheet_name='第一年', index=False)
    df_y2[['年度', 'KPI類別', 'KPI項目', '目標值', '權重', '負責單位']].to_excel(writer, sheet_name='第二年', index=False)
    df_y3[['年度', 'KPI類別', 'KPI項目', '目標值', '權重', '負責單位']].to_excel(writer, sheet_name='第三年', index=False)
    
    # 各單位分頁
    for unit in ['研發部', '製程部', '應用工程', '品保部']:
        df_unit = df_all[df_all['負責單位'] == unit][['年度', 'KPI類別', 'KPI項目', '目標值', '權重']]
        df_unit.to_excel(writer, sheet_name=f'{unit}', index=False)

print(f"\n✅ Excel檔案已儲存: {output_path}")
