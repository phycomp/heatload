# 建立DataFrame
df_y1 = pd.DataFrame(year1_data)
df_y1['年度'] = '第一年 (R2R小量出貨 + 技術驗證)'

df_y2 = pd.DataFrame(year2_data)
df_y2['年度'] = '第二年 (中期大量製程擴展)'

df_y3 = pd.DataFrame(year3_data)
df_y3['年度'] = '第三年 (規模化與技術領先)'

# 合併
df_all = pd.concat([df_y1, df_y2, df_y3], ignore_index=True)
df_all = df_all[['年度', 'KPI類別', 'KPI項目', '目標值', '權重', '負責單位']]

# 統計
print("=" * 60)
