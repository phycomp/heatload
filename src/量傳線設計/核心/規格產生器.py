"""規格產生器：整合三視圖 export 產出 xlsx。"""
from .三視圖 import LayoutCalculator, 繪制三視, 規格資框, 層疊結構, 匯出分頁

def 產生規格書(通道數=8, 訊號間距=2.0, 訊號寬度=35.0, 線總寬=17.0, 線長度=200.0):
    佈局 = LayoutCalculator(通道數=通道數, 訊號間距=訊號間距,
                            訊號寬度=訊號寬度, 線總寬=線總寬, 線長度=線長度)
    前視圖, 側視圖, 上視圖 = 繪制三視(佈局)
    資框 = 規格資框(佈局)
    層疊 = 層疊結構(佈局)
    試算表 = 匯出分頁(佈局, 前視圖, 側視圖, 上視圖, 規格=資框, 層疊=層疊)
    return 佈局, 試算表
